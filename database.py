def add_crowdsourced_photo(data: Dict[str, Any]) -> Dict[str, Any]:
    conn = get_connection()
    cur = conn.cursor()
    cur.execute(
        """
        INSERT INTO crowdsourced_photos (
            location_id, city, title, user_id, user_name,
            lat, lon, original_photo_url, restored_photo_url, description
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
        """,
        (
            data.get("location_id"),
            data.get("city", "Гомель"),
            data.get("title", "Архивное фото"),
            str(data.get("user_id", "anonymous")),
            data.get("user_name", "Житель города"),
            data.get("lat"),
            data.get("lon"),
            data["original_photo_url"],
            data["restored_photo_url"],
            data.get("description", ""),
        ),
    )
    new_id = cur.lastrowid
    if data.get("location_id") and data.get("update_location_photos"):
        loc_id = int(data["location_id"])
        cur.execute("SELECT photos_json FROM locations WHERE id = ?", (loc_id,))
        loc_row = cur.fetchone()
        existing_photos = []
        if loc_row and loc_row["photos_json"]:
            try:
                existing_photos = json.loads(loc_row["photos_json"])
            except Exception:
                existing_photos = []
        orig_u = data["original_photo_url"]
        rest_u = data["restored_photo_url"]
        new_item = {
            "url": orig_u,
            "thumb_url": orig_u[:-5] + "_thumb.webp" if orig_u.endswith(".webp") else orig_u,
            "restored_url": rest_u,
            "restored_thumb_url": rest_u[:-5] + "_thumb.webp" if rest_u.endswith(".webp") else rest_u,
            "is_archival": True,
            "caption": data.get("title", "Архивный снимок"),
        }
        existing_photos.insert(0, new_item)
        cur.execute(
            "UPDATE locations SET photo_before_url = ?, photo_after_url = ?, photos_json = ? WHERE id = ?",
            (
                data["original_photo_url"],
                data["restored_photo_url"],
                json.dumps(existing_photos, ensure_ascii=False),
                loc_id,
            ),
        )
    conn.commit()
    cur.execute("SELECT * FROM crowdsourced_photos WHERE id = ?", (new_id,))
    row = dict(cur.fetchone())
    conn.close()
    return row


