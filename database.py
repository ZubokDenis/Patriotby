def classify_location_tags(item: Dict[str, Any]) -> List[str]:
    raw_cat = (item.get("category") or "architecture").strip().lower()
    title_low = (item.get("title") or "").strip().lower()
    desc_low = (item.get("short_description") or "").strip().lower()

    if raw_cat == "archival":
        return ["archival"]

    if raw_cat == "nature":
        return ["nature"]

    tags = set()

    is_rel = raw_cat == "religious" or any(k in title_low for k in _RELIGIOUS_KEYWORDS) or any(
        k in desc_low for k in ("православный храм", "католический храм", "мужской монастырь", "женский монастырь", "старообрядческая церковь", "кафедральный собор")
    )
    if is_rel:
        tags.add("religious")

    if raw_cat == "ww2" or (not is_rel and any(k in title_low for k in _WW2_KEYWORDS)):
        tags.add("ww2")

    if raw_cat == "lost" or any(k in title_low for k in _LOST_KEYWORDS):
        tags.add("lost")
        if not is_rel:
            tags.add("historical")

    if any(k in title_low for k in _NATURE_KEYWORDS) and not is_rel and "ww2" not in tags:
        tags.add("nature")

    if raw_cat in ("architecture", "historical") and not is_rel and "ww2" not in tags:
        tags.add("architecture")
        tags.add("historical")

    if not tags:
        tags.add(raw_cat)

    return sorted(tags)


def matches_location_category(item: Dict[str, Any], cat_q: str) -> bool:
    if not cat_q or cat_q in ("all", "все"):
        return True
    c = cat_q.strip().lower()
    tags = item.get("tags") or classify_location_tags(item)
    raw_cat = (item.get("category") or "").strip().lower()
    if c == "religious":
        return "religious" in tags or raw_cat == "religious"
    if c in ("architecture", "historical"):
        if raw_cat == "archival":
            return False
        return "architecture" in tags or "historical" in tags or raw_cat in ("architecture", "historical")
    return c == raw_cat or c in tags


def row_to_dict(row: sqlite3.Row, include_embedding: bool = False) -> Dict[str, Any]:
    d = dict(row)
    if not include_embedding:
        d.pop("embedding", None)
    if "facts_json" in d:
        try:
            d["facts"] = json.loads(d.pop("facts_json") or "[]")
        except Exception:
            d["facts"] = []
    if "photos_json" in d:
        try:
            d["photos"] = json.loads(d.pop("photos_json") or "[]")
        except Exception:
            d["photos"] = []
    else:
        d["photos"] = []

    if not d["photos"] and d.get("photo_after_url"):
        d["photos"] = [
            {
                "url": d["photo_after_url"],
                "restored_url": None,
                "is_archival": False,
                "caption": "Фотография объекта",
            }
        ]
    d["tags"] = classify_location_tags(d)
    if d.get("category") == "architecture" and "religious" in d["tags"]:
        d["category"] = "religious"
    return d


def sync_vector_index() -> None:
    conn = get_connection()
    cur = conn.cursor()
    cur.execute("SELECT * FROM locations ORDER BY id ASC")
    raw_rows = cur.fetchall()

    clean_locs: List[Dict[str, Any]] = []
    embeddings = []
    to_update: List[Tuple[bytes, int]] = []

    for r in raw_rows:
        d_with_emb = row_to_dict(r, include_embedding=True)
        blob = d_with_emb.pop("embedding", None)
        vec = from_blob(blob) if isinstance(blob, (bytes, bytearray)) else None
        if vec is None:
            vec = encode_location(d_with_emb)
            to_update.append((to_blob(vec), int(d_with_emb["id"])))
        clean_locs.append(d_with_emb)
        embeddings.append(vec)

    if to_update:
        try:
            cur.executemany("UPDATE locations SET embedding = ? WHERE id = ?", to_update)
            conn.commit()
        except Exception:
            pass
    conn.close()

    vector_index.rebuild(clean_locs, embeddings)


