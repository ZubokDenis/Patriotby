DB_PATH = os.environ.get("PATRIOT_DB_PATH", "patriot.db")


def get_connection() -> sqlite3.Connection:
    conn = sqlite3.connect(DB_PATH, check_same_thread=False, timeout=20.0)
    conn.row_factory = sqlite3.Row
    try:
        conn.execute("PRAGMA journal_mode=WAL;")
        conn.execute("PRAGMA synchronous=NORMAL;")
    except Exception:
        pass
    return conn


def init_db() -> None:
    conn = get_connection()
    cur = conn.cursor()

    cur.execute(
        """
        CREATE TABLE IF NOT EXISTS locations (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            title TEXT NOT NULL,
            city TEXT NOT NULL,
            category TEXT NOT NULL,
            epoch TEXT NOT NULL,
            historical_person TEXT DEFAULT '',
            lat REAL NOT NULL,
            lon REAL NOT NULL,
            short_description TEXT NOT NULL,
            full_history TEXT NOT NULL,
            facts_json TEXT DEFAULT '[]',
            photo_before_url TEXT DEFAULT '',
            photo_after_url TEXT DEFAULT '',
            audio_script TEXT DEFAULT '',
            quest_question TEXT DEFAULT '',
            quest_answer TEXT DEFAULT '',
            quest_hint TEXT DEFAULT '',
            persona_name TEXT DEFAULT '',
            persona_role TEXT DEFAULT '',
            persona_epoch TEXT DEFAULT '',
            persona_prompt TEXT DEFAULT '',
            photos_json TEXT DEFAULT '[]',
            embedding BLOB DEFAULT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
        """
    )

    for alter_sql in (
        "ALTER TABLE locations ADD COLUMN photos_json TEXT DEFAULT '[]'",
        "ALTER TABLE locations ADD COLUMN embedding BLOB DEFAULT NULL",
        "CREATE INDEX IF NOT EXISTS idx_locations_city ON locations(city)",
        "CREATE INDEX IF NOT EXISTS idx_locations_category ON locations(category)",
    ):
        try:
            cur.execute(alter_sql)
            conn.commit()
        except Exception:
            pass

    cur.execute(
        """
        CREATE TABLE IF NOT EXISTS crowdsourced_photos (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            location_id INTEGER,
            city TEXT DEFAULT '',
            title TEXT NOT NULL,
            user_id TEXT DEFAULT 'anonymous',
            user_name TEXT DEFAULT 'Житель города',
            lat REAL,
            lon REAL,
            original_photo_url TEXT NOT NULL,
            restored_photo_url TEXT NOT NULL,
            description TEXT DEFAULT '',
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
        """
    )

    cur.execute(
        """
        CREATE TABLE IF NOT EXISTS user_progress (
            user_id TEXT PRIMARY KEY,
            user_name TEXT DEFAULT '',
            completed_quests_json TEXT DEFAULT '[]',
            points INTEGER DEFAULT 0,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
        """
    )

    conn.commit()

    seed_demo_data(conn)

    conn.close()
    sync_vector_index()


