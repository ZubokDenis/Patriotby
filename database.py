def record_quest_completion(user_id: str, user_name: str, location_id: int) -> Dict[str, Any]:
    conn = get_connection()
    cur = conn.cursor()
    cur.execute("SELECT * FROM user_progress WHERE user_id = ?", (str(user_id),))
    row = cur.fetchone()
    if not row:
        completed = [location_id]
        points = 100
        cur.execute(
            "INSERT INTO user_progress (user_id, user_name, completed_quests_json, points) VALUES (?, ?, ?, ?)",
            (str(user_id), user_name, json.dumps(completed), points),
        )
    else:
        completed = json.loads(row["completed_quests_json"] or "[]")
        points = int(row["points"] or 0)
        if location_id not in completed:
            completed.append(location_id)
            points += 100
            cur.execute(
                "UPDATE user_progress SET completed_quests_json = ?, points = ?, user_name = ?, updated_at = CURRENT_TIMESTAMP WHERE user_id = ?",
                (json.dumps(completed), points, user_name, str(user_id)),
            )
    conn.commit()
    conn.close()
    return {"user_id": user_id, "completed_quests": completed, "points": points}


