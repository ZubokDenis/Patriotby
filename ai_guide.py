def geocode_place(place_query: str) -> Optional[Dict[str, Any]]:
    raw = (place_query or "").strip()
    if not raw:
        return None
    low = raw.lower().replace("г.", "").replace("город", "").strip()

    if low in BELARUS_CITY_CENTERS:
        return dict(BELARUS_CITY_CENTERS[low])
    for k, val in BELARUS_CITY_CENTERS.items():
        if len(k) >= 4 and (low == k or low.startswith(k[:max(4, len(k) - 1)])):
            return dict(val)

    q = urllib.parse.quote(raw)
    urls_to_try = [
        f"https://nominatim.openstreetmap.org/search?q={q}&countrycodes=by&format=json&limit=1&accept-language=ru",
        f"https://nominatim.openstreetmap.org/search?q={q}&format=json&limit=1&accept-language=ru",
    ]
    for url in urls_to_try:
        try:
            req = urllib.request.Request(
                url,
                headers={"User-Agent": "PatriotHistoricalMiniApp/1.0 (Educational Project)"},
            )
            with urllib.request.urlopen(req, timeout=10) as resp:
                items = json.loads(resp.read().decode("utf-8"))
                if items:
                    item = items[0]
                    display = item.get("display_name", raw)
                    short_name = display.split(",")[0].strip()
                    return {
                        "name": short_name,
                        "display_name": display,
                        "lat": float(item["lat"]),
                        "lon": float(item["lon"]),
                    }
        except Exception as e:
            print(f"[Geocoder] Warning for {raw}: {e}")
    return None


def reverse_geocode(lat: float, lon: float) -> str:
    url = f"https://nominatim.openstreetmap.org/reverse?lat={lat}&lon={lon}&format=json&accept-language=ru"
    try:
        req = urllib.request.Request(
            url,
            headers={"User-Agent": "PatriotHistoricalMiniApp/1.0 (Educational Project)"},
        )
        with urllib.request.urlopen(req, timeout=8) as resp:
            data = json.loads(resp.read().decode("utf-8"))
            addr = data.get("address", {})
            city = (
                addr.get("city")
                or addr.get("town")
                or addr.get("village")
                or addr.get("municipality")
                or addr.get("state")
                or "Выбранная локация"
            )
            return city
    except Exception:
        return "Выбранная локация"


def haversine_km(lat1: float, lon1: float, lat2: float, lon2: float) -> float:
    r = 6371.0
    phi1, phi2 = math.radians(lat1), math.radians(lat2)
    dphi = math.radians(lat2 - lat1)
    dlambda = math.radians(lon2 - lon1)
    a = math.sin(dphi / 2.0) ** 2 + math.cos(phi1) * math.cos(phi2) * math.sin(dlambda / 2.0) ** 2
    return 2.0 * r * math.atan2(math.sqrt(a), math.sqrt(1.0 - a))


