def chat_with_historical_resident(
    location_id: int,
    user_message: str,
    history: Optional[List[Dict[str, str]]] = None,
) -> Dict[str, Any]:
    loc = get_location_by_id(location_id)
    if not loc:
        return {
            "reply": "Простите, путник, страницы этой летописи временно скрыты туманом времени.",
            "persona_name": "Хранитель истории",
            "persona_epoch": "XIX–XX вв.",
        }

    persona_name = loc.get("persona_name") or "Хранитель истории"
    persona_role = loc.get("persona_role") or "Очевидец эпохи"
    persona_epoch = loc.get("persona_epoch") or loc.get("epoch", "")
    facts_text = "\n".join([f"- {f}" for f in loc.get("facts", [])])

    system_prompt = f"""
Ты играешь роль исторического жителя в образовательно-патриотическом приложении.
Твоё имя: {persona_name} ({persona_role}).
Твоя эпоха: {persona_epoch}.
Город: {loc['city']}.
Объект, у которого вы находитесь: {loc['title']}.

Строгая краеведческая база фактов об этом месте (опирайся на неё и не выдумывай противоречащих небылиц):
Краткая справка: {loc['short_description']}
Полная история: {loc['full_history']}
Ключевые факты:
{facts_text}

Дополнительная ролевая инструкция: {loc.get('persona_prompt', '')}

Правила ответа:
1. Отвечай от первого лица в характерной, живой, уважительной манере своей эпохи.
2. Опирайся на реальные исторические факты об этом объекте и городе {loc['city']}.
3. Ответ должен быть ёмким и интересным (3–5 предложений), чтобы его было удобно читать со смартфона в Telegram Mini App.
"""

    conv_context = ""
    if history:
        for turn in history[-4:]:
            role_label = "Путник (Пользователь)" if turn.get("role") == "user" else persona_name
            conv_context += f"{role_label}: {turn.get('text', '')}\n"

    full_prompt = f"{conv_context}Путник (Пользователь): {user_message}\n{persona_name}:"
    ai_reply = call_gemini(full_prompt, system_instruction=system_prompt)

    if not ai_reply:
        facts_list = loc.get("facts", [])
        fact_snippet = facts_list[0] if facts_list else loc["short_description"]
        q_low = user_message.lower()
        if any(w in q_low for w in ["кто", "зовут", "ты", "вы", "привет", "здравств"]):
            ai_reply = (
                f"Приветствую вас в городе {loc['city']}! Я — {persona_name}, {persona_role.lower()} ({persona_epoch}). "
                f"Мы стоим у знакового места — «{loc['title']}». {loc['short_description']} "
                f"О чём именно из истории этого места вы хотели бы расспросить меня?"
            )
        elif any(w in q_low for w in ["загадк", "квест", "ответ", "подсказк", "колон", "год", "речк"]):
            ai_reply = (
                f"Хитрый вопрос! Как очевидец эпохи ({persona_epoch}), дам вам верную наводку: "
                f"{loc.get('quest_hint') or fact_snippet} Присмотритесь внимательнее к деталям «{loc['title']}»!"
            )
        else:
            ai_reply = (
                f"О, это славная страница нашей летописи ({persona_epoch})! {loc['full_history']} "
                f"Кстати, мало кто из нынешних гостей знает: {fact_snippet}"
            )

    return {
        "reply": ai_reply,
        "persona_name": persona_name,
        "persona_role": persona_role,
        "persona_epoch": persona_epoch,
        "location_title": loc["title"],
    }
