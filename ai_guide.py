def _order_stops_tsp_2opt(
    stops: List[Dict[str, Any]],
    user_lat: Optional[float],
    user_lon: Optional[float],
    c_lat: float,
    c_lon: float,
) -> List[Dict[str, Any]]:
    n = len(stops)
    if n <= 1:
        return list(stops)
    if n == 2:
        if user_lat is not None and user_lon is not None:
            d0 = haversine_km(user_lat, user_lon, float(stops[0]["lat"]), float(stops[0]["lon"]))
            d1 = haversine_km(user_lat, user_lon, float(stops[1]["lat"]), float(stops[1]["lon"]))
            return [stops[0], stops[1]] if d0 <= d1 else [stops[1], stops[0]]
        return list(stops)

    pool = list(stops)
    if user_lat is not None and user_lon is not None:
        pool.sort(key=lambda x: haversine_km(user_lat, user_lon, float(x["lat"]), float(x["lon"])))
    else:
        sub_lat = sum(float(x["lat"]) for x in pool) / n
        sub_lon = sum(float(x["lon"]) for x in pool) / n
        pool.sort(key=lambda x: haversine_km(sub_lat, sub_lon, float(x["lat"]), float(x["lon"])), reverse=True)

    tour: List[Dict[str, Any]] = [pool.pop(0)]
    while pool:
        curr = tour[-1]
        pool.sort(key=lambda x: haversine_km(float(curr["lat"]), float(curr["lon"]), float(x["lat"]), float(x["lon"])))
        tour.append(pool.pop(0))

    def _dist(a: Dict[str, Any], b: Dict[str, Any]) -> float:
        return haversine_km(float(a["lat"]), float(a["lon"]), float(b["lat"]), float(b["lon"]))

    improved = True
    iters = 0
    while improved and iters < 60:
        improved = False
        iters += 1
        for i in range(1, n - 1):
            for k in range(i + 1, n):
                before = _dist(tour[i - 1], tour[i]) + (
                    _dist(tour[k], tour[k + 1]) if k + 1 < n else 0.0
                )
                after = _dist(tour[i - 1], tour[k]) + (
                    _dist(tour[i], tour[k + 1]) if k + 1 < n else 0.0
                )
                if after + 1e-4 < before:
                    tour[i : k + 1] = reversed(tour[i : k + 1])
                    improved = True

    return tour


def _evaluate_tour_metrics(
    ordered_tour: List[Dict[str, Any]],
    speed_kmh: float,
    stop_minutes: float,
    user_lat: Optional[float],
    user_lon: Optional[float],
) -> Tuple[float, float, float]:
    if not ordered_tour:
        return 0.0, 0.0, 0.0

    total_dist_km = 0.0
    total_time_min = 0.0
    max_leg_min = 0.0

    curr_lat = user_lat if user_lat is not None else float(ordered_tour[0]["lat"])
    curr_lon = user_lon if user_lon is not None else float(ordered_tour[0]["lon"])

    for idx, loc in enumerate(ordered_tour):
        lat_f = float(loc["lat"])
        lon_f = float(loc["lon"])
        if idx > 0 or (user_lat is not None and user_lon is not None):
            raw_km = haversine_km(curr_lat, curr_lon, lat_f, lon_f)
            leg_km = raw_km * 1.22
            leg_min = (leg_km / speed_kmh) * 60.0
            if idx > 0 and leg_min > max_leg_min:
                max_leg_min = leg_min
        else:
            leg_km = 0.0
            leg_min = 0.0

        total_dist_km += leg_km
        total_time_min += leg_min + stop_minutes
        curr_lat, curr_lon = lat_f, lon_f

    return total_time_min, total_dist_km, max_leg_min


def _build_time_budgeted_route(
    candidate_locs: List[Dict[str, Any]],
    duration_minutes: int,
    transport_mode: str,
    speed_kmh: float,
    stop_minutes: float,
    max_stops: int,
    active_cats: List[str],
    sem_scores: Dict[int, float],
    user_lat: Optional[float],
    user_lon: Optional[float],
    c_lat: float,
    c_lon: float,
) -> List[Dict[str, Any]]:
    if not candidate_locs:
        return []
    if len(candidate_locs) == 1:
        item = dict(candidate_locs[0])
        r_km, sec_idx, sec_label = _compute_district_label_item(item, c_lat, c_lon)
        item["_r_km"] = r_km
        item["_sec_idx"] = sec_idx
        item["district_label"] = sec_label
        return [item]

    annotated: List[Dict[str, Any]] = []
    for loc in candidate_locs:
        r_km, sec_idx, sec_label = _compute_district_label_item(loc, c_lat, c_lon)
        item = dict(loc)
        item["_r_km"] = r_km
        item["_sec_idx"] = sec_idx
        item["district_label"] = sec_label
        annotated.append(item)

    time_budget = float(max(20, duration_minutes))
    hard_max_minutes = time_budget + 0.5

    if transport_mode == "walk":
        if duration_minutes <= 35:
            max_single_leg_min = 12.0
        elif duration_minutes <= 50:
            max_single_leg_min = 15.0
        elif duration_minutes <= 75:
            max_single_leg_min = 20.0
        elif duration_minutes <= 105:
            max_single_leg_min = 28.0
        else:
            max_single_leg_min = 45.0
    else:
        max_single_leg_min = max(12.0, time_budget * 0.42)

    cluster_radius_km = max(0.6, (time_budget / 60.0) * speed_kmh * 0.35 / 1.22)
    for a in annotated:
        neighbors = sum(
            1 for b in annotated
            if b is not a and haversine_km(float(a["lat"]), float(a["lon"]), float(b["lat"]), float(b["lon"])) <= cluster_radius_km
        )
        a["_density"] = neighbors

    seeds: List[Dict[str, Any]] = []
    seed_ids = set()

    def _add_seed(cand: Dict[str, Any]) -> None:
        cid = int(cand.get("id", 0))
        if cid not in seed_ids:
            seed_ids.add(cid)
            seeds.append(cand)

    if user_lat is not None and user_lon is not None:
        by_gps = sorted(
            annotated,
            key=lambda x: haversine_km(user_lat, user_lon, float(x["lat"]), float(x["lon"])),
        )
        for s in by_gps[:3]:
            _add_seed(s)
    else:
        by_density = sorted(
            annotated,
            key=lambda x: (
                x["_density"],
                sem_scores.get(int(x.get("id", 0)), 0.0),
                -x["_r_km"],
            ),
            reverse=True,
        )
        for s in by_density[:4]:
            _add_seed(s)

        by_center = sorted(annotated, key=lambda x: x["_r_km"])
        for s in by_center[:2]:
            _add_seed(s)

        if sem_scores:
            by_sem = sorted(
                annotated,
                key=lambda x: sem_scores.get(int(x.get("id", 0)), 0.0),
                reverse=True,
            )
            for s in by_sem[:2]:
                _add_seed(s)

        by_sec: Dict[int, List[Dict[str, Any]]] = {}
        for x in annotated:
            by_sec.setdefault(x["_sec_idx"], []).append(x)
        for sec_list in by_sec.values():
            sec_list.sort(key=lambda x: (x["_density"], sem_scores.get(int(x.get("id", 0)), 0.0)), reverse=True)
            _add_seed(sec_list[0])
            if len(seeds) >= 12:
                break

    wants_broad_overview = (duration_minutes >= 120) or (transport_mode in ("bike", "car") and duration_minutes >= 60)

    best_overall_tour: List[Dict[str, Any]] = []
    best_overall_Objective = -1e9

    for seed in seeds:
        selected: List[Dict[str, Any]] = [seed]
        selected_ids = {int(seed.get("id", 0))}
        cat_counts: Dict[str, int] = {str(seed.get("category", "architecture")): 1}
        sec_counts: Dict[int, int] = {int(seed.get("_sec_idx", -1)): 1}

        current_tour = list(selected)
        curr_time_min, _, _ = _evaluate_tour_metrics(
            current_tour, speed_kmh, stop_minutes, user_lat, user_lon
        )

        while len(selected) < max_stops:
            remaining = [x for x in annotated if int(x.get("id", 0)) not in selected_ids]
            if not remaining:
                break

            best_cand = None
            best_cand_tour = None
            best_cand_time = curr_time_min
            best_cand_score = -1e9

            for cand in remaining:
                min_raw_dist = min(
                    haversine_km(float(cand["lat"]), float(cand["lon"]), float(s["lat"]), float(s["lon"]))
                    for s in selected
                )
                min_leg_min = (min_raw_dist * 1.22 / speed_kmh) * 60.0
                if min_leg_min > max_single_leg_min * 1.25:
                    continue
                if curr_time_min + stop_minutes + min_leg_min * 0.5 > hard_max_minutes + 4.0:
                    continue

                trial_pool = selected + [cand]
                trial_tour = _order_stops_tsp_2opt(trial_pool, user_lat, user_lon, c_lat, c_lon)
                t_min, _, max_leg = _evaluate_tour_metrics(
                    trial_tour, speed_kmh, stop_minutes, user_lat, user_lon
                )

                if t_min > hard_max_minutes:
                    continue
                if max_leg > max_single_leg_min:
                    continue

                added_travel_min = max(0.0, (t_min - curr_time_min) - stop_minutes)
                cat_k = str(cand.get("category", "architecture"))
                sec_k = int(cand.get("_sec_idx", -1))
                lid = int(cand.get("id", 0))

                cat_bonus = 1.25 / (1.0 + cat_counts.get(cat_k, 0))
                sem_b = sem_scores.get(lid, 0.0) * 1.6
                non_arch_bonus = 0.45 if (cat_k != "archival" or "archival" in active_cats) else -0.45

                if wants_broad_overview:
                    sec_bonus = 0.65 / (1.0 + sec_counts.get(sec_k, 0))
                    dist_penalty = added_travel_min * 0.035
                    cand_score = cat_bonus + sec_bonus + sem_b + non_arch_bonus - dist_penalty
                else:
                    compact_bonus = max(0.0, (max_single_leg_min - added_travel_min) / max_single_leg_min) * 1.4
                    density_bonus = min(cand.get("_density", 0), 6) * 0.08
                    cand_score = compact_bonus + density_bonus + cat_bonus + sem_b + non_arch_bonus

                if cand_score > best_cand_score:
                    best_cand_score = cand_score
                    best_cand = cand
                    best_cand_tour = trial_tour
                    best_cand_time = t_min

            if best_cand is None or best_cand_tour is None:
                break

            selected.append(best_cand)
            selected_ids.add(int(best_cand.get("id", 0)))
            ck = str(best_cand.get("category", "architecture"))
            sk = int(best_cand.get("_sec_idx", -1))
            cat_counts[ck] = cat_counts.get(ck, 0) + 1
            sec_counts[sk] = sec_counts.get(sk, 0) + 1
            current_tour = best_cand_tour
            curr_time_min = best_cand_time

        if len(current_tour) == 1 and len(annotated) >= 2:
            remaining = [x for x in annotated if int(x.get("id", 0)) not in selected_ids]
            remaining.sort(
                key=lambda x: haversine_km(float(seed["lat"]), float(seed["lon"]), float(x["lat"]), float(x["lon"]))
            )
            closest = remaining[0]
            trial_tour = _order_stops_tsp_2opt([seed, closest], user_lat, user_lon, c_lat, c_lon)
            t_min, _, _ = _evaluate_tour_metrics(trial_tour, speed_kmh, stop_minutes, user_lat, user_lon)
            if t_min <= hard_max_minutes * 1.35:
                current_tour = trial_tour
                curr_time_min = t_min

        n_stops = len(current_tour)
        unique_cats = len({str(x.get("category", "architecture")) for x in current_tour})
        unique_secs = len({int(x.get("_sec_idx", -1)) for x in current_tour})
        sem_sum = sum(sem_scores.get(int(x.get("id", 0)), 0.0) for x in current_tour)
        time_utilization = 1.0 - min(1.0, abs(time_budget - curr_time_min) / time_budget)

        tour_objective = (
            (n_stops * 3.2)
            + (time_utilization * 2.5)
            + (unique_cats * 0.9)
            + (unique_secs * (0.75 if wants_broad_overview else 0.15))
            + (sem_sum * 1.4)
        )
        if n_stops >= 2 and tour_objective > best_overall_Objective:
            best_overall_Objective = tour_objective
            best_overall_tour = current_tour
        elif not best_overall_tour:
            best_overall_tour = current_tour

    return best_overall_tour


def generate_smart_route(
    user_query: str = "",
    city: str = "Гомель",
    duration_minutes: int = 180,
    transport_mode: str = "walk",
    categories: Optional[List[str]] = None,
    user_lat: Optional[float] = None,
    user_lon: Optional[float] = None,
) -> Dict[str, Any]:
    target_city = (city or "Гомель").strip()

    if user_query.strip():
        resolved_q_city = resolve_existing_city(user_query)
        if resolved_q_city:
            target_city = resolved_q_city
        else:
            extracted_city = _extract_city_from_query(user_query, default_city=target_city)
            if extracted_city:
                target_city = extracted_city

    candidate_locs = get_locations(city=target_city)
    if not candidate_locs and user_lat is not None and user_lon is not None:
        all_locs = get_locations()
        near_gps = [loc for loc in all_locs if haversine_km(user_lat, user_lon, loc["lat"], loc["lon"]) <= 20.0]
        if near_gps:
            candidate_locs = near_gps
            target_city = near_gps[0]["city"]

    if len(candidate_locs) < _min_expected_city_objects(target_city):
        geo_info, expanded_locs = generate_locations_for_place(
            place_name=target_city,
            center_lat=user_lat,
            center_lon=user_lon,
            user_interest=user_query,
        )
        if expanded_locs:
            candidate_locs = expanded_locs
            target_city = geo_info["name"]

    all_city_pool = list(candidate_locs)

    active_cats: List[str] = [c.strip().lower() for c in (categories or []) if c and c.strip().lower() != "all"]
    query_cats = _extract_categories_from_query(user_query)
    if not active_cats and query_cats:
        active_cats = query_cats

    if active_cats:
        filtered = [
            loc for loc in candidate_locs
            if any(matches_location_category(loc, c) for c in active_cats)
        ]
        supp_key = f"{target_city.strip().lower()}::{','.join(sorted(active_cats))}"
        if len(filtered) < 5 and supp_key not in _EXPANDED_CITIES_CACHE:
            _EXPANDED_CITIES_CACHE.add(supp_key)
            extra_locs = _supplement_city_category_locations(target_city, all_city_pool, active_cats)
            if extra_locs:
                all_city_pool.extend(extra_locs)
                filtered = [
                    loc for loc in all_city_pool
                    if any(matches_location_category(loc, c) for c in active_cats)
                ]
        if filtered:
            candidate_locs = filtered
    else:
        physical_locs = [loc for loc in candidate_locs if loc.get("category") != "archival"]
        archival_locs = [loc for loc in candidate_locs if loc.get("category") == "archival"]
        if len(physical_locs) >= 6:
            candidate_locs = physical_locs + archival_locs[:2]

    ref_pool = all_city_pool if all_city_pool else candidate_locs
    c_lat = sum(float(x["lat"]) for x in ref_pool) / max(1, len(ref_pool))
    c_lon = sum(float(x["lon"]) for x in ref_pool) / max(1, len(ref_pool))

    effective_user_lat: Optional[float] = None
    effective_user_lon: Optional[float] = None
    if user_lat is not None and user_lon is not None and candidate_locs:
        min_gps_dist = min(
            haversine_km(user_lat, user_lon, float(loc["lat"]), float(loc["lon"]))
            for loc in candidate_locs
        )
        if min_gps_dist <= 4.5:
            effective_user_lat = user_lat
            effective_user_lon = user_lon

    sem_scores: Dict[int, float] = {}
    if user_query.strip() and candidate_locs:
        q_vec = encode_text(user_query, title_boost=user_query)
        for loc in candidate_locs:
            loc_id = int(loc.get("id", 0))
            sem_scores[loc_id] = float(np.dot(encode_location(loc), q_vec))

    speed_map = {
        "walk": 4.8,
        "bike": 15.0,
        "car": 32.0,
    }
    speed_kmh = speed_map.get(transport_mode, 4.8)

    if duration_minutes <= 50:
        stop_minutes = 5.0
    elif duration_minutes <= 75:
        stop_minutes = 6.0
    else:
        stop_minutes = 7.0

    if duration_minutes >= 150:
        max_stops = 16
    elif duration_minutes >= 110:
        max_stops = 13
    elif duration_minutes >= 80:
        max_stops = 10
    elif duration_minutes >= 55:
        max_stops = 8
    elif duration_minutes >= 40:
        max_stops = 6
    else:
        max_stops = 5

    ordered_raw = _build_time_budgeted_route(
        candidate_locs=candidate_locs,
        duration_minutes=duration_minutes,
        transport_mode=transport_mode,
        speed_kmh=speed_kmh,
        stop_minutes=stop_minutes,
        max_stops=max_stops,
        active_cats=active_cats,
        sem_scores=sem_scores,
        user_lat=effective_user_lat,
        user_lon=effective_user_lon,
        c_lat=c_lat,
        c_lon=c_lon,
    )

    ordered_stops: List[Dict[str, Any]] = []
    total_distance_km = 0.0
    total_time_min = 0.0
    curr_lat = effective_user_lat if effective_user_lat is not None else (float(ordered_raw[0]["lat"]) if ordered_raw else c_lat)
    curr_lon = effective_user_lon if effective_user_lon is not None else (float(ordered_raw[0]["lon"]) if ordered_raw else c_lon)
    covered_districts: List[str] = []

    for idx, loc in enumerate(ordered_raw):
        dist = (
            haversine_km(curr_lat, curr_lon, float(loc["lat"]), float(loc["lon"]))
            if (idx > 0 or effective_user_lat is not None)
            else 0.0
        )
        walk_dist = dist * 1.22
        travel_min = (walk_dist / speed_kmh) * 60.0
        total_distance_km += walk_dist
        total_time_min += travel_min + stop_minutes
        curr_lat, curr_lon = float(loc["lat"]), float(loc["lon"])

        _, _, dist_label = _compute_bearing_and_sector(curr_lat, curr_lon, c_lat, c_lon)
        if dist_label not in covered_districts:
            covered_districts.append(dist_label)

        cat_slug = str(loc.get("category", "architecture"))
        stop_copy = dict(loc)
        stop_copy.pop("_r_km", None)
        stop_copy.pop("_sec_idx", None)
        stop_copy.pop("_density", None)
        stop_copy["leg_distance_km"] = round(walk_dist, 2)
        stop_copy["leg_time_min"] = max(1, round(travel_min)) if (idx > 0 or effective_user_lat is not None) else 0
        stop_copy["stop_minutes"] = int(stop_minutes)
        stop_copy["district_label"] = dist_label
        stop_copy["category_label"] = _ROUTE_CATEGORY_LABELS.get(cat_slug, "Историческое наследие")
        ordered_stops.append(stop_copy)

    estimated_minutes = max(10, round(total_time_min))
    stops_summary = "\n".join(
        [
            f"{i+1}. {s['title']} ({s.get('district_label', '')}, {s.get('category_label', '')}, переход ~{s.get('leg_time_min', 0)} мин) — {s['short_description']}"
            for i, s in enumerate(ordered_stops)
        ]
    )
    transport_ru = {"walk": "пешком", "bike": "на велосипеде", "car": "на автомобиле"}.get(transport_mode, "пешком")
    selected_cats_ru = [
        _ROUTE_CATEGORY_LABELS.get(c, c) for c in active_cats
    ] if active_cats else ["Все категории наследия"]
    cats_summary_str = ", ".join(dict.fromkeys(selected_cats_ru))
    districts_str = ", ".join(covered_districts[:5])

    ai_intro = None
    if _resolve_gemini_api_key():
        prompt = (
            f"Ты — увлекательный ИИ-экскурсовод проекта «Патриот». Пользователь построил маршрут в городе {target_city} "
            f"на {duration_minutes} мин ({transport_ru}, расчётное время с осмотром: ~{estimated_minutes} мин, "
            f"дистанция: {round(total_distance_km, 2)} км, точек: {len(ordered_stops)}, район(ы): {districts_str}, категории: {cats_summary_str}). "
            f"{f'Пожелание пользователя: {user_query}.' if user_query else ''}\n"
            f"Точки маршрута:\n{stops_summary}\n\n"
            "Напиши живое, вдохновляющее вступление экскурсовода к этому маршруту (3-4 предложения), "
            "отметь удобство темпа прогулки и логичную связку локаций по времени, и пожелай удачи в квесте!"
        )
        ai_intro = call_gemini(prompt)

    if not ai_intro:
        if duration_minutes <= 65 and transport_mode == "walk":
            ai_intro = (
                f"Компактный прогулочный маршрут по городу {target_city} ({transport_ru}, ~{estimated_minutes} мин · {round(total_distance_km, 2)} км) готов! "
                f"Мы подобрали {len(ordered_stops)} знаковых мест в удобной пешей доступности друг от друга ({districts_str}, категории: {cats_summary_str}), "
                f"чтобы вы спокойно осмотрели каждую локацию и уложились в выбранное время. "
                f"На точках маршрута вас ждут архивные и современные кадры, ИИ-реставрация «До / После» и вопросы квеста!"
            )
        else:
            ai_intro = (
                f"Маршрут по городу {target_city} ({transport_ru}, ~{estimated_minutes} мин · {round(total_distance_km, 2)} км) сформирован! "
                f"В маршрут вошли {len(ordered_stops)} знаковых мест ({districts_str}, категории: {cats_summary_str}), "
                f"выстроенных в оптимальную цепочку с учётом времени на переходы и осмотр каждой точки. "
                f"На каждой локации вас ждут архивные и современные кадры, нейро-реставрация «До / После» и вопросы краеведческого квеста!"
            )

    return {
        "city": target_city,
        "transport_mode": transport_mode,
        "transport_label": transport_ru,
        "selected_categories": active_cats if active_cats else ["all"],
        "selected_categories_label": cats_summary_str,
        "covered_districts": covered_districts,
        "requested_minutes": duration_minutes,
        "estimated_minutes": estimated_minutes,
        "total_distance_km": round(total_distance_km, 2),
        "ai_narrative": ai_intro,
        "stops": ordered_stops,
    }


