def _compute_bearing_and_sector(lat: float, lon: float, c_lat: float, c_lon: float) -> Tuple[float, int, str]:
    dist_km = haversine_km(c_lat, c_lon, lat, lon)
    if dist_km < 0.42:
        return dist_km, -1, "Центральная часть"
    dy = lat - c_lat
    dx = (lon - c_lon) * math.cos(math.radians(c_lat))
    angle_deg = (math.degrees(math.atan2(dx, dy)) + 360.0) % 360.0
    sec_idx = int(((angle_deg + 22.5) % 360.0) // 45.0) % 8
    return dist_km, sec_idx, _SECTOR_NAMES_RU[sec_idx]


