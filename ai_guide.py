GEMINI_API_KEY = os.environ.get("GEMINI_API_KEY", "")


def _resolve_gemini_api_key() -> str:
    key = os.environ.get("GEMINI_API_KEY", GEMINI_API_KEY).strip()
    if key:
        return key
    try:
        env_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), ".env_keys.json")
        if os.path.exists(env_path):
            with open(env_path, "r", encoding="utf-8") as f:
                return str(json.load(f).get("GEMINI_API_KEY", "")).strip()
    except Exception:
        pass
    return ""


def call_gemini(prompt: str, system_instruction: str = "", json_mode: bool = False) -> Optional[str]:
    api_key = _resolve_gemini_api_key()
    if not api_key:
        return None

    models_to_try = ["gemini-3.5-flash-lite", "gemini-flash-lite-latest"]
    url_tmpl = "https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent?key={key}"

    for model_name in models_to_try:
        url = url_tmpl.format(model=model_name, key=api_key)
        payload: Dict[str, Any] = {
            "contents": [{"role": "user", "parts": [{"text": prompt}]}],
            "generationConfig": {
                "temperature": 0.68,
                "maxOutputTokens": 1024,
            },
        }
        if system_instruction:
            payload["systemInstruction"] = {"parts": [{"text": system_instruction}]}
        if json_mode:
            payload["generationConfig"]["responseMimeType"] = "application/json"

        try:
            req = urllib.request.Request(
                url,
                data=json.dumps(payload).encode("utf-8"),
                headers={"Content-Type": "application/json"},
                method="POST",
            )
            with urllib.request.urlopen(req, timeout=6.5) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                candidates = data.get("candidates", [])
                if candidates:
                    parts = candidates[0].get("content", {}).get("parts", [])
                    for part in reversed(parts):
                        if isinstance(part, dict) and part.get("text"):
                            return str(part["text"]).strip()
        except Exception as e:
            print(f"[Gemini API] {model_name} attempt note: {e}")
            continue
    return None


