def _fetch_city_pastvu_pool(lat0: float, lon0: float, distance_m: int = 10000, limit: int = 45) -> List[Dict[str, Any]]:
    params = json.dumps({"geo": [round(lat0, 5), round(lon0, 5)], "distance": distance_m, "limit": limit, "year2": 1986})
    api_url = f"https://pastvu.com/api2?method=photo.giveNearestPhotos&params={urllib.parse.quote(params)}"
    ua = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0.0.0 Safari/124.0"
    pool_items: List[Dict[str, Any]] = []
    try:
        req = urllib.request.Request(api_url, headers={"User-Agent": ua})
        with urllib.request.urlopen(req, timeout=3.2) as resp:
            data = json.loads(resp.read().decode("utf-8", errors="ignore"))
            photos = (data.get("result") or {}).get("photos") or []
            for p in photos:
                f_rel = p.get("file")
                geo_pt = p.get("geo")
                if not f_rel or not isinstance(geo_pt, list) or len(geo_pt) < 2:
                    continue
                plat, plon = float(geo_pt[0]), float(geo_pt[1])
                if haversine_km(lat0, lon0, plat, plon) > 12.0:
                    continue
                ptitle = (p.get("title") or "Исторический кадр").strip()
                year = p.get("year") or "XX век"
                caption = f"Архивный снимок ({year} г.): {ptitle}" if p.get("year") else f"Архивный снимок: {ptitle}"
                pool_items.append(
                    {
                        "url": f"https://pastvu.com/_p/a/{f_rel}",
                        "caption": caption,
                        "ptitle": ptitle,
                        "year": year,
                        "has_exact_year": bool(p.get("year")),
                        "lat": round(plat, 6),
                        "lon": round(plon, 6),
                    }
                )
    except Exception as e:
        print(f"[City PastVu Pool] Note at ({lat0}, {lon0}): {e}")
    return pool_items


